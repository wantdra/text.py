function createCloze(letter, targets) {
  const replacements = new Map();
  const pattern = new RegExp(`\\b(${targets.map((w) => escapeRegExp(w)).join("|")})\\b`, "gi");
  let counter = 0;

  const cloze = letter.replace(pattern, (match) => {
    counter += 1;
    replacements.set(counter, match);
    const blanks = "_".repeat(Math.max(6, match.length));
    return `[${counter}] ${blanks}`;
  });

  return { cloze, replacements };
}

function escapeRegExp(text) {
  return text.replace(/[.*+?^${}()|[\\]\\]/g, "\\$&");
}

function renderParagraphs(element, text) {
  element.replaceChildren();
  const paragraphs = text.trim().split(/\n\s*\n/);
  for (const part of paragraphs) {
    const p = document.createElement("p");
    p.textContent = part.trim();
    element.appendChild(p);
  }
}

function renderTemplate(template) {
  renderParagraphs(document.getElementById("scenario-tr"), template.scenarioTr);
  renderParagraphs(document.getElementById("scenario-de"), template.scenarioDe);
  renderParagraphs(document.getElementById("letter-de"), template.letterDe);
  renderParagraphs(document.getElementById("letter-tr"), template.letterTr);

  const { cloze, replacements } = createCloze(
    template.letterDe,
    template.clozeTargets
  );
  renderParagraphs(document.getElementById("cloze-text"), cloze);

  const answerList = document.getElementById("cloze-answers");
  answerList.replaceChildren();
  for (const [index, value] of replacements.entries()) {
    const li = document.createElement("li");
    li.textContent = `${index}. ${value}`;
    answerList.appendChild(li);
  }
}

function showPanel(panelId) {
  const examplePanel = document.getElementById("example-panel");
  const clozePanel = document.getElementById("cloze-panel");
  examplePanel.hidden = panelId !== "example";
  clozePanel.hidden = panelId !== "cloze";
}

document.addEventListener("DOMContentLoaded", () => {
  const select = document.getElementById("template-select");
  templates.forEach((template) => {
    const option = document.createElement("option");
    option.value = template.id;
    option.textContent = template.title;
    select.appendChild(option);
  });

  const updateTemplate = () => {
    const selected = templates.find((item) => item.id === select.value);
    if (selected) {
      renderTemplate(selected);
    }
  };

  select.addEventListener("change", () => {
    updateTemplate();
    showPanel("example");
  });

  document.getElementById("show-example").addEventListener("click", () => {
    showPanel("example");
  });

  document.getElementById("show-cloze").addEventListener("click", () => {
    showPanel("cloze");
  });

  if (templates.length > 0) {
    select.value = templates[0].id;
    updateTemplate();
    showPanel("example");
  }
});

